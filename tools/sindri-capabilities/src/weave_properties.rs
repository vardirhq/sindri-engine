//! The Weave properties Sindri applies, as a description something else can
//! read.
//!
//! Read from [`sindri_weave::PROPERTIES`], which is the table the bridge
//! filters every declaration by, so a property listed here is one Sindri
//! applies and one Sindri applies is listed here. Whether a property inherits
//! is the language's own list, [`weave::INHERITED`], and whether it is a
//! shorthand is asked of the language's expansion, so neither is restated.

use std::fmt::Write as _;

use serde_json::{Value, json};
use sindri_weave::{PROPERTIES, Property};

/// Whether the language expands `name` into longhands before Sindri sees it.
fn is_shorthand(property: &Property, name: &str) -> bool {
    weave::shorthand::expand(name, property.example).is_some()
}

fn inherits(name: &str) -> bool {
    weave::INHERITED.contains(&name)
}

pub(crate) fn describe() -> Value {
    let properties: Vec<Value> = PROPERTIES
        .iter()
        .map(|property| {
            json!({
                "names": property.names,
                "group": property.group,
                "values": property.values,
                "writes": property.writes,
                "summary": property.summary,
                "example": property.example,
                "inherited": property.names.iter().any(|name| inherits(name)),
                "shorthand": property.names.iter().any(|name| is_shorthand(property, name)),
            })
        })
        .collect();
    json!({
        "schema_version": crate::SCHEMA_VERSION,
        "engine_version": env!("CARGO_PKG_VERSION"),
        "generated_by": crate::REGENERATE_COMMAND,
        "about": "Every property a Weave stylesheet may declare for Sindri UI: its names, the \
                  values it accepts, the Sindri UI data it writes, and a value that applies. \
                  A property not listed is ignored. Read from the table `sindri-weave` applies \
                  declarations by. docs/weave-reference.md describes the language itself: \
                  selectors, the cascade, lengths, colors and responsive rules.",
        "properties": properties,
    })
}

/// The same table, rendered for a person.
pub(crate) fn render() -> String {
    let mut page = String::from(
        "# Weave properties\n\n\
         <!-- Generated by `cargo run -p sindri-capabilities -- --write`. Do not edit by hand: \
         a test fails when\nthis file disagrees with the property table in `sindri-weave`. -->\n\n\
         Every property a Weave stylesheet may declare for Sindri UI in this build of the \
         engine,\nread from the table the bridge applies declarations by. A property not \
         listed here is\nignored.\n\n\
         The language itself (selectors, the cascade, `var()`, lengths, colors and \
         responsive\nrules) is described in [`docs/weave-reference.md`](../weave-reference.md). \
         A length is\n`px`, `vw`, `vh`, `%`, a plain number in overlay units, or `calc(…)`; a \
         color is\n`#rgb`, `#rgba`, `#rrggbb`, `#rrggbbaa`, `transparent`, `black` or `white`.\n\n\
         The machine-readable form of this page is\n\
         [`weave-reference.json`](weave-reference.json).\n",
    );
    let mut group = "";
    for property in PROPERTIES {
        if property.group != group {
            group = property.group;
            let _ = write!(page, "\n## {group}\n");
        }
        push_property(&mut page, property);
    }
    page
}

fn push_property(page: &mut String, property: &Property) {
    let names: Vec<String> = property
        .names
        .iter()
        .map(|name| format!("`{name}`"))
        .collect();
    let _ = write!(
        page,
        "\n### {}\n\n{}\n\n",
        names.join(", "),
        property.summary
    );
    let _ = writeln!(page, "- **Values:** {}", property.values);
    let _ = writeln!(page, "- **Writes:** {}", property.writes);
    let _ = writeln!(
        page,
        "- **Example:** `{}: {};`",
        property.names[0], property.example
    );
    if property.names.iter().any(|name| inherits(name)) {
        let _ = writeln!(
            page,
            "- **Inherited:** an element without its own value takes its parent's."
        );
    }
    let shorthands: Vec<String> = property
        .names
        .iter()
        .filter(|name| is_shorthand(property, name))
        .map(|name| format!("`{name}`"))
        .collect();
    if !shorthands.is_empty() {
        let _ = writeln!(
            page,
            "- **Shorthand:** {} is expanded into its longhands where it is written, so a \
             later longhand overrides one part of it.",
            shorthands.join(", ")
        );
    }
}
